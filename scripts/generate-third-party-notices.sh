#!/usr/bin/env bash
# Writes the licences of the libraries compiled into the released binaries to
# THIRD-PARTY-NOTICES.txt. Run it again after adding or upgrading a dependency and
# commit the result: tests/third_party_notices.rs fails until the file matches
# Cargo.lock.
#
# Needs cargo-about (`cargo install cargo-about --locked --features cli`) and
# python3. Settings, including the release targets, are in about.toml.
#
# piigrep itself is dropped from the list: it is published to crates.io, so
# `publish = false` cannot keep it out. Its licence is LICENSE, shown ahead of
# this file by `piigrep --license`.
set -euo pipefail

cd "$(dirname "$0")/.."

OUT="THIRD-PARTY-NOTICES.txt"

if ! cargo about --version >/dev/null 2>&1; then
  echo "Error: cargo-about is not installed. Run: cargo install cargo-about --locked --features cli" >&2
  exit 1
fi
if ! command -v python3 >/dev/null 2>&1; then
  echo "Error: python3 is required." >&2
  exit 1
fi

WORK=$(mktemp -d)
# Written next to the output rather than in /tmp: a mv across file systems is a
# copy, and one stopped halfway would leave a broken file behind.
TMP=$(mktemp "${OUT}.XXXXXX")
trap 'rm -rf "$WORK" "$TMP"' EXIT

# --fail: a crate whose licence cannot be worked out fails the run instead of
# being left out with a warning.
cargo about generate -c about.toml --locked --fail --format json -o "$WORK/about.json"

python3 - "$WORK/about.json" > "$TMP" <<'PYTHON'
import json
import sys

OWN_CRATES = {"piigrep"}

with open(sys.argv[1], encoding="utf-8") as f:
    report = json.load(f)

# One entry per licence text, as cargo-about gives it: crates that ship the same
# text share an entry.
entries = {}
for licence in report["licenses"]:
    users = entries.setdefault((licence["id"], licence["text"]), {})
    for used in licence["used_by"]:
        crate = used["crate"]
        if crate["name"] in OWN_CRATES:
            continue
        users[(crate["name"], crate["version"])] = crate.get("repository") or ""

out = sys.stdout
out.write(
    "THIRD-PARTY NOTICES\n"
    "\n"
    "piigrep bundles the open source libraries listed below. Each entry gives the\n"
    "license, the packages it applies to, and the license text as shipped by the\n"
    "package. Generated by scripts/generate-third-party-notices.sh; do not edit by hand.\n"
    "\n"
    "piigrep itself is under the MIT License; see LICENSE.\n"
    "\n"
    + "#" * 80 + "\n"
    "# Rust crates (compiled into the binary)\n"
    + "#" * 80 + "\n"
    "\n"
)

# Sorted so that a rerun over the same Cargo.lock gives the same file.
def order(item):
    (spdx, text), users = item
    return (spdx, min(users), text)

listed = sorted(((k, v) for k, v in entries.items() if v), key=order)
last = listed[-1][0]
for (spdx, text), users in listed:
    out.write("=" * 80 + "\n")
    out.write(f"License: {spdx}\n\n")
    out.write("Used by:\n")
    for (name, version), repository in sorted(users.items()):
        suffix = f" ({repository})" if repository else ""
        out.write(f"  {name} {version}{suffix}\n")
    out.write("\n")
    out.write(text.rstrip() + "\n")
    # A blank line between entries, none after the last.
    if (spdx, text) != last:
        out.write("\n")
PYTHON

# mktemp creates the file 0600; the notices are not a secret.
chmod 644 "$TMP"
mv "$TMP" "$OUT"
echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
